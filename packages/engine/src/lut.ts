export function wrapAngle(angle: number): number {
  return angle & 255;
}

export function stepFixed(xFp: number, yFp: number, heading: number, speedFp: number): { xFp: number; yFp: number } {
  const a = wrapAngle(heading);
  return {
    xFp: xFp + ((speedFp * COS[a]) >> FP_SHIFT),
    yFp: yFp + ((speedFp * SIN[a]) >> FP_SHIFT),
  };
}

export function cellOf(fp: number): number {
  return fp >> FP_SHIFT;
}

export function toFp(cell: number): number {
  return (cell << FP_SHIFT) + (FP >> 1);
}

export function headingFromDirection(direction: string): number {
  switch (direction) {
    case 'RIGHT':
      return 0;
    case 'DOWN':
      return 64;
    case 'LEFT':
      return 128;
    case 'UP':
      return 192;
    default:
      return 0;
  }
}

export function directionFromHeading(heading: number): Direction {
  const q = (wrapAngle(heading + 32) >> 6) & 3;
  return [Direction.RIGHT, Direction.DOWN, Direction.LEFT, Direction.UP][q];
}
